// Dev tool: writes src/pcb/stroke-font.ts from the public-domain Hershey "Sans 1-stroke" (futural)
// glyphs in the hersheytext package, normalised so cap height = 1 and the baseline is y = 0 (y up).
// A freely available single-stroke sans for PCB text.
// Usage: node tools/gen-stroke-font.mjs
import { readFileSync, writeFileSync } from "node:fs"
const font = JSON.parse(readFileSync("node_modules/hersheytext/hersheytext.json", "utf8")).futural
const BASE = 22 // Hershey y of the baseline in this set (cap tops at 1)
const CAP = 21
const glyphs = font.chars.map((c, k) => {
	const strokes = []
	for (const part of c.d.split("M").map(s => s.trim()).filter(Boolean)) {
		const nums = part.replace("L", " ").trim().split(/[\s,]+/).map(Number)
		const pts = []
		for (let n = 0; n + 1 < nums.length; n += 2) pts.push(+(nums[n] / CAP).toFixed(4), +((BASE - nums[n + 1]) / CAP).toFixed(4))
		strokes.push(pts)
	}
	return { ch: String.fromCharCode(33 + k), w: +((2 * c.o) / CAP).toFixed(4), strokes }
})
glyphs.unshift({ ch: " ", w: 16 / CAP, strokes: [] }) // the set starts at "!"; a space is 16 units wide
const out = `// Generated by tools/gen-stroke-font.mjs from the Hershey "Sans 1-stroke" font (public domain,
// via the MIT-licensed hersheytext package). Cap height 1, baseline y = 0, y up; w = advance.
export interface StrokeGlyph {
	w: number
	strokes: number[][] // polylines as flat x,y lists
}

export const STROKE_GLYPHS: Record<string, StrokeGlyph> = ${JSON.stringify(Object.fromEntries(glyphs.map(g => [g.ch, { w: g.w, strokes: g.strokes }])))}
`
writeFileSync("src/pcb/stroke-font.ts", out)
console.log("glyphs", glyphs.length, "bytes", out.length)
